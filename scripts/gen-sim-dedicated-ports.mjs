/**
 * Generate a dedicated handler stub for every combat-override item.
 * Family catch-alls are not “done” — each itemId gets its own handlerId.
 *
 *   node scripts/gen-sim-dedicated-ports.mjs
 *
 * Writes:
 *   assets/data/sim-port-registry.json
 *   js/pages/sim/engine/scripts/dedicated/*.js  (generated — do not hand-edit)
 */
import fs from 'fs';
import path from 'path';

const INV = 'assets/data/sim-item-inventory.json';
const OUT_REG = 'assets/data/sim-port-registry.json';
const OUT_DIR = 'js/pages/sim/engine/scripts/dedicated';

/** Reviewed = hand ports + auto-pattern ports */
const REVIEWED_FILE = 'assets/data/sim-reviewed-ids.json';
const REVIEWED = Object.create(null);
if (fs.existsSync(REVIEWED_FILE)) {
  for (const id of JSON.parse(fs.readFileSync(REVIEWED_FILE, 'utf8')).ids || []) {
    REVIEWED[id] = true;
  }
}
for (const id of ["broom","banana","poison_bow","hero_longsword","falcon_blade","healing_herbs","wooden_sword","katana","amulet_of_life","holy_armor"]) REVIEWED[id] = true;

/** Skip non-placeable base scripts if present. */
const SKIP_IDS = new Set(['weapon', 'item', 'bow', 'food', 'pet', 'card', 'gem']);

/**
 * Assign roadmap band from inventory family / overrides.
 * @param {object} entry
 */
function assignBand(entry) {
  const fam = entry.family || 'unique';
  const o = new Set(entry.overrides || []);
  if (fam === 'basic_weapon' || fam === 'weapon_base') return 'I';
  if (fam === 'on_hit') return 'J';
  if (fam === 'synergy_aura') return 'M';
  if (fam === 'start_buff' || fam === 'pet_like' || fam === 'food') return 'N';
  if (fam === 'unique') return 'O';
  if (fam === 'custom_cd') {
    // Split custom_cd alphabetically into K / L for manageable waves
    const id = entry.id || '';
    return id < 'n' ? 'K' : 'L';
  }
  if (o.has('doCooldownEffect')) return 'K';
  return 'O';
}

/**
 * Pick family template handler for stub body.
 * @param {object} entry
 */
function templateFor(entry) {
  const fam = entry.family || '';
  const o = new Set(entry.overrides || []);
  if (fam === 'synergy_aura') return 'empower_aura';
  if (fam === 'start_buff' || fam === 'food') return 'start_regen';
  if (fam === 'pet_like') return 'pet_strike';
  if (fam === 'on_hit' && /poison|blood|dagger|bow/i.test(entry.id)) {
    return 'poison_weapon';
  }
  if (o.has('onCombatStart') && !o.has('doCooldownEffect')) return 'start_regen';
  if (fam === 'basic_weapon' || fam === 'weapon_base') return 'basic_cd';
  return 'basic_cd';
}

const BAND_META = {
  I: {
    title: 'Core weapons',
    file: 'band-i-weapons.js',
    desc: 'basic_weapon + weapon_base',
  },
  J: {
    title: 'On-hit weapons',
    file: 'band-j-onhit.js',
    desc: 'on_hit family',
  },
  K: {
    title: 'Custom CD A–M',
    file: 'band-k-custom-am.js',
    desc: 'custom_cd id < n',
  },
  L: {
    title: 'Custom CD N–Z',
    file: 'band-l-custom-nz.js',
    desc: 'custom_cd id >= n',
  },
  M: {
    title: 'Synergy auras',
    file: 'band-m-auras.js',
    desc: 'synergy_aura',
  },
  N: {
    title: 'Start buffs / pets / food',
    file: 'band-n-start-pets.js',
    desc: 'start_buff, pet_like, food',
  },
  O: {
    title: 'Uniques / outliers',
    file: 'band-o-uniques.js',
    desc: 'unique + leftovers',
  },
};

const inv = JSON.parse(fs.readFileSync(INV, 'utf8'));
/** @type {Record<string, object>} */
const byId = {};
/** @type {Record<string, object[]>} */
const byBand = { I: [], J: [], K: [], L: [], M: [], N: [], O: [] };

for (const [id, entry] of Object.entries(inv.byId || {})) {
  if (SKIP_IDS.has(id)) continue;
  const band = assignBand(entry);
  const template = templateFor(entry);
  const fidelity = REVIEWED[id] ? 'reviewed' : 'stub';
  const row = {
    id,
    band,
    family: entry.family,
    scriptStem: entry.scriptStem,
    file: entry.file,
    overrides: entry.overrides || [],
    template,
    handlerId: id,
    fidelity,
  };
  byId[id] = row;
  byBand[band].push(row);
}

fs.mkdirSync(OUT_DIR, { recursive: true });

const banner = `/**
 * GENERATED by scripts/gen-sim-dedicated-ports.mjs — do not hand-edit.
 * Raise fidelity via scripts/ports.js + registry REVIEWED, then re-run generator.
 */
`;

function emitBandFile(bandKey, rows) {
  const meta = BAND_META[bandKey];
  const lines = [
    banner,
    `import { HANDLERS } from '../handlers.js';`,
    ``,
    `/** @param {string} id @param {string} family @param {string} template */`,
    `function stub(id, family, template) {`,
    `  const base = HANDLERS[template] || HANDLERS.basic_cd;`,
    `  return {`,
    `    handlerId: id,`,
    `    family,`,
    `    onCombatStart: base.onCombatStart,`,
    `    onCooldownEffect: base.onCooldownEffect,`,
    `  };`,
    `}`,
    ``,
    `/** Band ${bandKey} — ${meta.title}: ${meta.desc} (${rows.length} items) */`,
    `/** @type {Record<string, import('../handlers.js').ScriptHandler>} */`,
    `export const HANDLERS_${bandKey} = {`,
  ];
  for (const row of rows.sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(
      `  ${JSON.stringify(row.id)}: stub(${JSON.stringify(row.id)}, ${JSON.stringify(row.family || 'custom_cd')}, ${JSON.stringify(row.template)}), // ${row.fidelity} · ${row.file}`,
    );
  }
  lines.push(`};`);
  lines.push(``);
  const outPath = path.join(OUT_DIR, meta.file);
  fs.writeFileSync(outPath, lines.join('\n'));
  return meta.file;
}

const generatedFiles = [];
for (const key of Object.keys(BAND_META)) {
  generatedFiles.push(emitBandFile(key, byBand[key]));
}

const indexLines = [
  banner,
  ...generatedFiles.map((f, i) => {
    const key = Object.keys(BAND_META)[i];
    return `import { HANDLERS_${key} } from './${f}';`;
  }),
  ``,
  `/** @type {Record<string, import('../handlers.js').ScriptHandler>} */`,
  `export const DEDICATED_HANDLERS = {`,
  ...Object.keys(BAND_META).map((k) => `  ...HANDLERS_${k},`),
  `};`,
  ``,
  `export function listDedicatedIds() {`,
  `  return Object.keys(DEDICATED_HANDLERS);`,
  `}`,
  ``,
];
fs.writeFileSync(path.join(OUT_DIR, 'index.js'), indexLines.join('\n'));

const totals = {
  entries: Object.keys(byId).length,
  stub: Object.values(byId).filter((r) => r.fidelity === 'stub').length,
  reviewed: Object.values(byId).filter((r) => r.fidelity === 'reviewed').length,
  byBand: Object.fromEntries(
    Object.keys(BAND_META).map((k) => [k, byBand[k].length]),
  ),
};

const registry = {
  generatedAt: new Date().toISOString(),
  inventoryExtractedAt: inv.extractedAt,
  goal: 'Every placeable combat item has a dedicated handlerId (not a family catch-all). Raise fidelity stub → reviewed → parity.',
  skipIds: [...SKIP_IDS],
  reviewedIds: Object.keys(REVIEWED),
  bands: BAND_META,
  totals,
  byId,
};

fs.writeFileSync(OUT_REG, JSON.stringify(registry, null, 2));

console.log(
  `Port registry: ${totals.entries} dedicated (${totals.reviewed} reviewed, ${totals.stub} stub)`,
);
console.log('Bands:', totals.byBand);
console.log(`Wrote ${OUT_REG} + ${OUT_DIR}/`);
